-- Skrzynka nadawcza powiadomien (transactional outbox): wpis powstaje w tej samej
-- transakcji co zmiana biznesowa, wiec awaria aplikacji nie gubi powiadomien.
CREATE TABLE powiadomienia (
    id_powiadomienia NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rezerwacji NUMBER NOT NULL,
    opoznienie_min NUMBER(4,0) NOT NULL,
    kanal         VARCHAR2(5) NOT NULL,
    odbiorca      VARCHAR2(120) NOT NULL,
    tresc         VARCHAR2(400) NOT NULL,
    status        VARCHAR2(8) DEFAULT 'NOWE' NOT NULL,
    proby         NUMBER(2,0) DEFAULT 0 NOT NULL,
    nastepna_proba TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ostatni_blad  VARCHAR2(200),
    utworzono     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    wyslano       TIMESTAMP,
    CONSTRAINT uq_pow_zdarzenie UNIQUE (id_rezerwacji, opoznienie_min, kanal),
    CONSTRAINT fk_pow_rez FOREIGN KEY (id_rezerwacji) REFERENCES rezerwacje (id_rezerwacji),
    CONSTRAINT chk_pow_kanal CHECK (kanal IN ('SMS', 'EMAIL')),
    CONSTRAINT chk_pow_status CHECK (status IN ('NOWE', 'W_TOKU', 'WYSLANE', 'MARTWE'))
);
-- Indeks czesciowy: NULL-e nie trafiaja do indeksu, wiec trzyma tylko sprawy otwarte
-- i nie rosnie wraz z historia. Dla W_TOKU nastepna_proba pelni role dzierzawy:
-- po awarii pracownika termin mija i wiersz sam wraca do kolejki.
CREATE INDEX ix_pow_do_wysylki ON powiadomienia (
    CASE WHEN status IN ('NOWE', 'W_TOKU') THEN nastepna_proba END
);

-- Kolejka polecen dla centrali; odbiera ja makieta-bridge.
CREATE TABLE h0_kolejka_dcc (
    id_zadania    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_kursu      NUMBER,
    typ_polecenia VARCHAR2(10) NOT NULL,
    adres_dcc     NUMBER(5,0),
    ramka_hex     VARCHAR2(40) NOT NULL,
    opis          VARCHAR2(200) NOT NULL,
    status        VARCHAR2(9) DEFAULT 'NOWE' NOT NULL,
    proby         NUMBER(2,0) DEFAULT 0 NOT NULL,
    utworzono     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    wyslano       TIMESTAMP,
    CONSTRAINT fk_dcc_kurs FOREIGN KEY (id_kursu) REFERENCES h0_harmonogram_kursow (id_kursu),
    CONSTRAINT chk_dcc_typ CHECK (typ_polecenia IN ('PREDKOSC', 'FUNKCJA', 'ROZJAZD', 'STOP_AWAR')),
    CONSTRAINT chk_dcc_status CHECK (status IN ('NOWE', 'WYSLANE', 'BLAD', 'ANULOWANE'))
);
CREATE INDEX ix_dcc_kurs ON h0_kolejka_dcc (id_kursu);
CREATE INDEX ix_dcc_do_wysylki ON h0_kolejka_dcc (
    CASE WHEN status = 'NOWE' THEN id_zadania END
);

-- Dziennik powypadkowy zmian stanu infrastruktury. Tylko dopisywanie.
CREATE TABLE h0_audyt_infrastruktury (
    id_wpisu      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    obiekt        VARCHAR2(10) NOT NULL,
    id_obiektu    NUMBER NOT NULL,
    kod_obiektu   VARCHAR2(10) NOT NULL,
    atrybut       VARCHAR2(30) NOT NULL,
    wartosc_przed VARCHAR2(30),
    wartosc_po    VARCHAR2(30),
    uzytkownik    VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
    modul         VARCHAR2(64)  DEFAULT SYS_CONTEXT('USERENV', 'MODULE'),
    czas          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT chk_audyt_obiekt CHECK (obiekt IN ('BLOK', 'ROZJAZD'))
);
CREATE INDEX ix_audyt_obiekt ON h0_audyt_infrastruktury (obiekt, id_obiektu, czas);

-- Zapis przez transakcje autonomiczna, aby przetrwal ROLLBACK operacji biznesowej.
CREATE TABLE dziennik_bledow (
    id_bledu      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    zrodlo        VARCHAR2(60) NOT NULL,
    kod_bledu     NUMBER,
    komunikat     VARCHAR2(4000),
    stos          VARCHAR2(4000),
    kontekst      VARCHAR2(400),
    czas          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE OR REPLACE TRIGGER trg_audyt_niezmienny
BEFORE UPDATE OR DELETE ON h0_audyt_infrastruktury
BEGIN
    RAISE_APPLICATION_ERROR(-20990, 'Dziennik powypadkowy jest tylko do dopisywania.');
END;
/

CREATE OR REPLACE TRIGGER trg_audyt_rozjazdy
AFTER UPDATE OF polozenie_aktualne, status_grzania ON h0_rozjazdy
FOR EACH ROW
BEGIN
    IF :OLD.polozenie_aktualne <> :NEW.polozenie_aktualne THEN
        INSERT INTO h0_audyt_infrastruktury (obiekt, id_obiektu, kod_obiektu, atrybut, wartosc_przed, wartosc_po)
        VALUES ('ROZJAZD', :NEW.id_rozjazdu, :NEW.kod_rozjazdu, 'POLOZENIE', :OLD.polozenie_aktualne, :NEW.polozenie_aktualne);
    END IF;
    IF :OLD.status_grzania <> :NEW.status_grzania THEN
        INSERT INTO h0_audyt_infrastruktury (obiekt, id_obiektu, kod_obiektu, atrybut, wartosc_przed, wartosc_po)
        VALUES ('ROZJAZD', :NEW.id_rozjazdu, :NEW.kod_rozjazdu, 'GRZANIE', :OLD.status_grzania, :NEW.status_grzania);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_audyt_bloki
AFTER UPDATE OF status_blokady ON h0_bloki_torowe
FOR EACH ROW
WHEN (OLD.status_blokady <> NEW.status_blokady)
BEGIN
    INSERT INTO h0_audyt_infrastruktury (obiekt, id_obiektu, kod_obiektu, atrybut, wartosc_przed, wartosc_po)
    VALUES ('BLOK', :NEW.id_bloku, :NEW.kod_bloku, 'STATUS', :OLD.status_blokady, :NEW.status_blokady);
END;
/
