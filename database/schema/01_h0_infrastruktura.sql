-- 1. TOPOLOGIA MAKIETY -------------------------------------------------------

CREATE TABLE h0_bloki_torowe (
    id_bloku           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod_bloku          VARCHAR2(10) NOT NULL,
    dlugosc_mm         NUMBER(5,0)  NOT NULL,              -- dlugosc fizyczna toru
    max_predkosc_dcc   NUMBER(3,0)  DEFAULT 126 NOT NULL,  -- limit kroku DCC na bloku (0-126)
    adres_s88          NUMBER(4,0)  NOT NULL,              -- adres czujnika zajetosci
    status_blokady     VARCHAR2(21) DEFAULT 'WOLNY' NOT NULL,
    id_kursu_przebiegu NUMBER,                             -- kurs, dla ktorego blok jest zamkniety
    CONSTRAINT uq_blok_kod UNIQUE (kod_bloku),
    CONSTRAINT uq_blok_s88 UNIQUE (adres_s88),
    CONSTRAINT chk_status_bloku CHECK (status_blokady IN ('WOLNY', 'PRZEBIEG', 'ZAJETY', 'ZABLOKOWANY_AWARYJNIE')),
    CONSTRAINT chk_dlugosc_mm CHECK (dlugosc_mm > 0),
    CONSTRAINT chk_blok_predkosc CHECK (max_predkosc_dcc BETWEEN 0 AND 126),
    -- PRZEBIEG oznacza zawsze przydzial do konkretnego kursu.
    CONSTRAINT chk_przebieg_ma_kurs CHECK (status_blokady <> 'PRZEBIEG' OR id_kursu_przebiegu IS NOT NULL)
);

CREATE TABLE h0_rozjazdy (
    id_rozjazdu        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod_rozjazdu       VARCHAR2(10) NOT NULL,
    adres_dcc_akces    NUMBER(4,0)  NOT NULL,              -- adres dekodera akcesoriow DCC
    polozenie_aktualne VARCHAR2(10) DEFAULT 'PROSTO' NOT NULL,
    status_grzania     VARCHAR2(5)  DEFAULT 'OFF' NOT NULL, -- miniaturowa grzalka rozjazdu
    pobor_grzalki_ma   NUMBER(4,0)  DEFAULT 120 NOT NULL,
    CONSTRAINT uq_rozjazd_kod UNIQUE (kod_rozjazdu),
    CONSTRAINT uq_rozjazd_adres UNIQUE (adres_dcc_akces),
    CONSTRAINT chk_adres_akces CHECK (adres_dcc_akces BETWEEN 1 AND 2044),
    CONSTRAINT chk_polozenie CHECK (polozenie_aktualne IN ('PROSTO', 'ZWROTNA')),
    CONSTRAINT chk_grzanie CHECK (status_grzania IN ('ON', 'OFF'))
);

-- Graf skierowany torow. Krawedz przez rozjazd wymaga jego okreslonego polozenia.
CREATE TABLE h0_polaczenia_blokow (
    id_bloku_z         NUMBER NOT NULL,
    id_bloku_do        NUMBER NOT NULL,
    id_rozjazdu        NUMBER,
    wymagane_polozenie VARCHAR2(10),
    CONSTRAINT pk_polaczenia_blokow PRIMARY KEY (id_bloku_z, id_bloku_do),
    CONSTRAINT fk_polacz_z FOREIGN KEY (id_bloku_z) REFERENCES h0_bloki_torowe (id_bloku),
    CONSTRAINT fk_polacz_do FOREIGN KEY (id_bloku_do) REFERENCES h0_bloki_torowe (id_bloku),
    CONSTRAINT fk_polacz_rozjazd FOREIGN KEY (id_rozjazdu) REFERENCES h0_rozjazdy (id_rozjazdu),
    CONSTRAINT chk_polacz_petla CHECK (id_bloku_z <> id_bloku_do),
    CONSTRAINT chk_polacz_polozenie CHECK (
        (id_rozjazdu IS NULL AND wymagane_polozenie IS NULL)
        OR (id_rozjazdu IS NOT NULL AND wymagane_polozenie IN ('PROSTO', 'ZWROTNA')))
);
CREATE INDEX ix_polacz_do ON h0_polaczenia_blokow (id_bloku_do);
CREATE INDEX ix_polacz_rozjazd ON h0_polaczenia_blokow (id_rozjazdu);

-- Wydajnosc pradowa centrali; jeden wiersz = jeden boost.
CREATE TABLE h0_centrale (
    id_centrali        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa              VARCHAR2(40) NOT NULL,
    limit_pradu_ma     NUMBER(5,0)  NOT NULL,
    CONSTRAINT uq_centrala_nazwa UNIQUE (nazwa),
    CONSTRAINT chk_limit_pradu CHECK (limit_pradu_ma > 0)
);

-- 2. TABOR W SKALI 1:87 ------------------------------------------------------

CREATE TABLE h0_lokomotywy (
    id_lokomotywy      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa_modelu       VARCHAR2(50) NOT NULL,
    producent_modelu   VARCHAR2(30),
    adres_dcc_loco     NUMBER(5,0)  NOT NULL,              -- 1-127 krotki, 128-10239 dlugi
    masa_g             NUMBER(4,0)  NOT NULL,
    dlugosc_ze_sprzegiem_mm NUMBER(4,0) NOT NULL,
    max_uciag_g        NUMBER(5,0)  NOT NULL,              -- maks. masa ciagnionego skladu
    max_pobor_pradu_ma NUMBER(4,0)  NOT NULL,
    v_max_skalowana    NUMBER(3,0)  NOT NULL,              -- km/h po przeliczeniu 1:87
    CONSTRAINT uq_loco_adres UNIQUE (adres_dcc_loco),
    CONSTRAINT chk_adres_dcc CHECK (adres_dcc_loco BETWEEN 1 AND 10239),
    CONSTRAINT chk_masa CHECK (masa_g > 0),
    CONSTRAINT chk_loco_dlugosc CHECK (dlugosc_ze_sprzegiem_mm > 0),
    CONSTRAINT chk_loco_uciag CHECK (max_uciag_g > 0),
    CONSTRAINT chk_loco_vmax CHECK (v_max_skalowana > 0)
);

CREATE TABLE h0_wagony (
    id_wagonu          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nr_inwentarzowy    VARCHAR2(20) NOT NULL,
    typ_wagonu         VARCHAR2(20) NOT NULL,              -- np. Bmnopux, Eanos
    kategoria          VARCHAR2(15) NOT NULL,
    dlugosc_ze_sprzegiem_mm NUMBER(4,0) NOT NULL,
    masa_g             NUMBER(4,0)  NOT NULL,
    liczba_miejsc      NUMBER(3,0)  DEFAULT 0 NOT NULL,    -- miejsca w skali 1:1
    wymaga_oswietlenia VARCHAR2(1)  DEFAULT 'N' NOT NULL,
    pobor_oswietlenia_ma NUMBER(4,0) DEFAULT 0 NOT NULL,
    CONSTRAINT uq_wagon_nr UNIQUE (nr_inwentarzowy),
    CONSTRAINT chk_kat_wagonu CHECK (kategoria IN ('PASAZERSKI', 'TOWAROWY')),
    CONSTRAINT chk_oswietlenie CHECK (wymaga_oswietlenia IN ('T', 'N')),
    CONSTRAINT chk_wagon_dlugosc CHECK (dlugosc_ze_sprzegiem_mm > 0),
    CONSTRAINT chk_wagon_masa CHECK (masa_g > 0),
    CONSTRAINT chk_wagon_miejsca CHECK (kategoria = 'PASAZERSKI' OR liczba_miejsc = 0)
);
CREATE INDEX ix_wagon_kategoria ON h0_wagony (kategoria);

-- 3. REGULY POGODOWE I PLAN RUCHU --------------------------------------------

-- Reguly sa danymi, nie kodem: nowy scenariusz nie wymaga zmiany pakietu.
CREATE TABLE h0_polityki_pogodowe (
    scenariusz_pogodowy VARCHAR2(15) PRIMARY KEY,
    mnoznik_predkosci   NUMBER(3,2) NOT NULL,   -- sliskie szyny / ograniczenia upalowe
    mnoznik_uciagu      NUMBER(3,2) NOT NULL,   -- spadek przyczepnosci
    grzanie_rozjazdow   VARCHAR2(1) NOT NULL,
    dodatek_pradu_wagon_ma NUMBER(4,0) NOT NULL, -- ogrzewanie / klimatyzacja skladu
    CONSTRAINT chk_pol_predkosc CHECK (mnoznik_predkosci > 0 AND mnoznik_predkosci <= 1),
    CONSTRAINT chk_pol_uciag CHECK (mnoznik_uciagu > 0 AND mnoznik_uciagu <= 1),
    CONSTRAINT chk_pol_grzanie CHECK (grzanie_rozjazdow IN ('T', 'N'))
);

CREATE TABLE h0_harmonogram_kursow (
    id_kursu            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identyfikator_rejsu VARCHAR2(15) NOT NULL,
    id_bloku_start      NUMBER NOT NULL,
    id_bloku_meta       NUMBER NOT NULL,
    godzina_odjazdu     TIMESTAMP NOT NULL,
    prognoza_frekwencji_procent NUMBER(3,0) DEFAULT 50 NOT NULL,
    popyt_bazowy_miejsc NUMBER(4,0) DEFAULT 240 NOT NULL,  -- 100% frekwencji dla tej relacji
    scenariusz_pogodowy VARCHAR2(15) DEFAULT 'STANDARD' NOT NULL,
    id_lokomotywy       NUMBER,                            -- przydzielana przez optymalizator
    status_kursu        VARCHAR2(12) DEFAULT 'PLANOWANY' NOT NULL,
    predkosc_docelowa_kmh NUMBER(3,0),
    miejsca_w_skladzie  NUMBER(4,0),
    CONSTRAINT fk_kurs_blok_start FOREIGN KEY (id_bloku_start) REFERENCES h0_bloki_torowe (id_bloku),
    CONSTRAINT fk_kurs_blok_meta FOREIGN KEY (id_bloku_meta) REFERENCES h0_bloki_torowe (id_bloku),
    CONSTRAINT fk_kurs_pogoda FOREIGN KEY (scenariusz_pogodowy) REFERENCES h0_polityki_pogodowe (scenariusz_pogodowy),
    CONSTRAINT fk_kurs_loco FOREIGN KEY (id_lokomotywy) REFERENCES h0_lokomotywy (id_lokomotywy),
    CONSTRAINT chk_frekwencja CHECK (prognoza_frekwencji_procent BETWEEN 0 AND 100),
    CONSTRAINT chk_kurs_trasa CHECK (id_bloku_start <> id_bloku_meta),
    CONSTRAINT chk_kurs_status CHECK (status_kursu IN ('PLANOWANY', 'PRZYGOTOWANY', 'W_TRASIE', 'ZAKONCZONY', 'ODWOLANY'))
);
-- Klucze obce bez indeksu powoduja blokade calej tabeli podrzednej przy DML rodzica.
CREATE INDEX ix_kurs_blok_start ON h0_harmonogram_kursow (id_bloku_start);
CREATE INDEX ix_kurs_blok_meta ON h0_harmonogram_kursow (id_bloku_meta);
CREATE INDEX ix_kurs_pogoda ON h0_harmonogram_kursow (scenariusz_pogodowy);
CREATE INDEX ix_kurs_loco_status ON h0_harmonogram_kursow (id_lokomotywy, status_kursu);
CREATE INDEX ix_kurs_status ON h0_harmonogram_kursow (status_kursu);

ALTER TABLE h0_bloki_torowe ADD CONSTRAINT fk_blok_kurs
    FOREIGN KEY (id_kursu_przebiegu) REFERENCES h0_harmonogram_kursow (id_kursu);
CREATE INDEX ix_blok_kurs ON h0_bloki_torowe (id_kursu_przebiegu);

-- 4. WYNIKI OPTYMALIZACJI ----------------------------------------------------

CREATE TABLE h0_aktywne_sklady (
    id_kursu           NUMBER NOT NULL,
    id_wagonu          NUMBER NOT NULL,
    pozycja_w_skladzie NUMBER(2,0) NOT NULL,
    CONSTRAINT pk_aktywne_sklady PRIMARY KEY (id_kursu, id_wagonu),
    CONSTRAINT uq_sklad_pozycja UNIQUE (id_kursu, pozycja_w_skladzie),
    CONSTRAINT fk_sklad_kurs FOREIGN KEY (id_kursu) REFERENCES h0_harmonogram_kursow (id_kursu),
    CONSTRAINT fk_sklad_wagon FOREIGN KEY (id_wagonu) REFERENCES h0_wagony (id_wagonu),
    CONSTRAINT chk_sklad_pozycja CHECK (pozycja_w_skladzie >= 1)
);
CREATE INDEX ix_sklad_wagon ON h0_aktywne_sklady (id_wagonu);

-- Zamkniety przebieg kursu: kolejne bloki i wymagane polozenia rozjazdow.
CREATE TABLE h0_przebiegi (
    id_kursu           NUMBER NOT NULL,
    kolejnosc          NUMBER(3,0) NOT NULL,
    id_bloku           NUMBER NOT NULL,
    id_rozjazdu        NUMBER,
    wymagane_polozenie VARCHAR2(10),
    CONSTRAINT pk_przebiegi PRIMARY KEY (id_kursu, kolejnosc),
    CONSTRAINT uq_przebieg_blok UNIQUE (id_kursu, id_bloku),
    CONSTRAINT fk_przebieg_kurs FOREIGN KEY (id_kursu) REFERENCES h0_harmonogram_kursow (id_kursu),
    CONSTRAINT fk_przebieg_blok FOREIGN KEY (id_bloku) REFERENCES h0_bloki_torowe (id_bloku),
    CONSTRAINT fk_przebieg_rozjazd FOREIGN KEY (id_rozjazdu) REFERENCES h0_rozjazdy (id_rozjazdu)
);
CREATE INDEX ix_przebieg_blok ON h0_przebiegi (id_bloku);
CREATE INDEX ix_przebieg_rozjazd ON h0_przebiegi (id_rozjazdu);
