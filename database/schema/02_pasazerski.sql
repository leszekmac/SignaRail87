-- ============================================================================
-- MODUL 02: rozklad jazdy i sprzedaz miejsc
-- Warstwa logiczna kolei. Lacznikami z makieta sa stacje.id_bloku_h0,
-- kursy_rozkladowe.id_kursu_h0 oraz wagony (h0_wagony) i ich miejsca.
-- ============================================================================

CREATE TABLE stacje (
    id_stacji    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod_stacji   VARCHAR2(8)  NOT NULL,
    nazwa        VARCHAR2(60) NOT NULL,
    id_bloku_h0  NUMBER,
    CONSTRAINT uq_stacja_kod UNIQUE (kod_stacji),
    CONSTRAINT fk_stacja_blok FOREIGN KEY (id_bloku_h0) REFERENCES h0_bloki_torowe (id_bloku)
);
CREATE INDEX ix_stacja_blok ON stacje (id_bloku_h0);

CREATE TABLE linie_kolejowe (
    id_linii     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numer_linii  VARCHAR2(10) NOT NULL,
    nazwa        VARCHAR2(80) NOT NULL,
    CONSTRAINT uq_linia_numer UNIQUE (numer_linii)
);

CREATE TABLE odcinki_linii (
    id_linii     NUMBER NOT NULL,
    kolejnosc    NUMBER(3,0) NOT NULL,
    id_stacji_od NUMBER NOT NULL,
    id_stacji_do NUMBER NOT NULL,
    dlugosc_km   NUMBER(6,1) NOT NULL,
    CONSTRAINT pk_odcinki_linii PRIMARY KEY (id_linii, kolejnosc),
    CONSTRAINT fk_odcinek_linia FOREIGN KEY (id_linii) REFERENCES linie_kolejowe (id_linii),
    CONSTRAINT fk_odcinek_od FOREIGN KEY (id_stacji_od) REFERENCES stacje (id_stacji),
    CONSTRAINT fk_odcinek_do FOREIGN KEY (id_stacji_do) REFERENCES stacje (id_stacji),
    CONSTRAINT chk_odcinek_stacje CHECK (id_stacji_od <> id_stacji_do),
    CONSTRAINT chk_odcinek_km CHECK (dlugosc_km > 0)
);
CREATE INDEX ix_odcinek_od ON odcinki_linii (id_stacji_od);
CREATE INDEX ix_odcinek_do ON odcinki_linii (id_stacji_do);

CREATE TABLE pociagi (
    id_pociagu    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numer_pociagu VARCHAR2(10) NOT NULL,
    nazwa         VARCHAR2(40),
    kategoria     VARCHAR2(5)  NOT NULL,
    CONSTRAINT uq_pociag_numer UNIQUE (numer_pociagu),
    CONSTRAINT chk_pociag_kat CHECK (kategoria IN ('EIP', 'IC', 'TLK', 'R'))
);

-- Wzorzec trasy: czasy jako minuty od polnocy dnia kursu (moga przekraczac 1440).
CREATE TABLE postoje_wzorcowe (
    id_pociagu   NUMBER NOT NULL,
    lp           NUMBER(3,0) NOT NULL,
    id_stacji    NUMBER NOT NULL,
    minuta_przyjazdu NUMBER(5,0) NOT NULL,
    minuta_odjazdu   NUMBER(5,0) NOT NULL,
    km_od_startu NUMBER(6,1) NOT NULL,
    CONSTRAINT pk_postoje_wzorcowe PRIMARY KEY (id_pociagu, lp),
    CONSTRAINT uq_wzorzec_stacja UNIQUE (id_pociagu, id_stacji),
    CONSTRAINT fk_pw_trasa_pociag FOREIGN KEY (id_pociagu) REFERENCES pociagi (id_pociagu),
    CONSTRAINT fk_pw_trasa_stacja FOREIGN KEY (id_stacji) REFERENCES stacje (id_stacji),
    CONSTRAINT chk_wzorzec_czas CHECK (minuta_odjazdu >= minuta_przyjazdu)
);
CREATE INDEX ix_wzorzec_stacja ON postoje_wzorcowe (id_stacji);

-- Staly sklad handlowy pociagu.
CREATE TABLE pociagi_wagony (
    id_pociagu   NUMBER NOT NULL,
    nr_wagonu    NUMBER(2,0) NOT NULL,
    id_wagonu    NUMBER NOT NULL,
    CONSTRAINT pk_pociagi_wagony PRIMARY KEY (id_pociagu, nr_wagonu),
    CONSTRAINT uq_pociag_wagon UNIQUE (id_pociagu, id_wagonu),
    CONSTRAINT fk_pw_pociag FOREIGN KEY (id_pociagu) REFERENCES pociagi (id_pociagu),
    CONSTRAINT fk_pw_wagon FOREIGN KEY (id_wagonu) REFERENCES h0_wagony (id_wagonu)
);
CREATE INDEX ix_pw_wagon ON pociagi_wagony (id_wagonu);

CREATE TABLE miejsca (
    id_miejsca   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_wagonu    NUMBER NOT NULL,
    nr_miejsca   NUMBER(3,0) NOT NULL,
    klasa        NUMBER(1,0) NOT NULL,
    przy_oknie   VARCHAR2(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT uq_miejsce UNIQUE (id_wagonu, nr_miejsca),
    CONSTRAINT fk_miejsce_wagon FOREIGN KEY (id_wagonu) REFERENCES h0_wagony (id_wagonu),
    CONSTRAINT chk_miejsce_klasa CHECK (klasa IN (1, 2)),
    CONSTRAINT chk_miejsce_okno CHECK (przy_oknie IN ('T', 'N'))
);

CREATE TABLE taryfy (
    kategoria    VARCHAR2(5) NOT NULL,
    klasa        NUMBER(1,0) NOT NULL,
    stawka_km    NUMBER(6,3) NOT NULL,
    oplata_minimalna NUMBER(8,2) NOT NULL,
    CONSTRAINT pk_taryfy PRIMARY KEY (kategoria, klasa)
);

CREATE TABLE kursy_rozkladowe (
    id_kursu     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pociagu   NUMBER NOT NULL,
    data_kursu   DATE   NOT NULL,
    status       VARCHAR2(10) DEFAULT 'PLANOWY' NOT NULL,
    opoznienie_min NUMBER(4,0) DEFAULT 0 NOT NULL,
    powod_opoznienia VARCHAR2(200),
    id_kursu_h0  NUMBER,
    CONSTRAINT uq_kurs_dzien UNIQUE (id_pociagu, data_kursu),
    CONSTRAINT fk_kr_pociag FOREIGN KEY (id_pociagu) REFERENCES pociagi (id_pociagu),
    CONSTRAINT fk_kr_h0 FOREIGN KEY (id_kursu_h0) REFERENCES h0_harmonogram_kursow (id_kursu),
    CONSTRAINT chk_kr_status CHECK (status IN ('PLANOWY', 'OPOZNIONY', 'ODWOLANY')),
    CONSTRAINT chk_kr_data CHECK (data_kursu = TRUNC(data_kursu)),
    CONSTRAINT chk_kr_opozn CHECK (opoznienie_min >= 0)
);
CREATE INDEX ix_kr_h0 ON kursy_rozkladowe (id_kursu_h0);

-- Rzeczywisty rozklad: jeden wiersz = postoj konkretnego kursu.
-- Partycje miesieczne: wyszukiwanie zawsze dotyczy waskiego okna czasu,
-- a archiwizacja to DROP PARTITION zamiast masowego DELETE.
CREATE TABLE kursy_postoje (
    id_kursu     NUMBER NOT NULL,
    lp           NUMBER(3,0) NOT NULL,
    id_stacji    NUMBER NOT NULL,
    przyjazd     DATE NOT NULL,
    odjazd       DATE NOT NULL,
    km_od_startu NUMBER(6,1) NOT NULL,
    CONSTRAINT pk_kursy_postoje PRIMARY KEY (id_kursu, lp),
    CONSTRAINT fk_kp_kurs FOREIGN KEY (id_kursu) REFERENCES kursy_rozkladowe (id_kursu),
    CONSTRAINT fk_kp_stacja FOREIGN KEY (id_stacji) REFERENCES stacje (id_stacji),
    CONSTRAINT chk_kp_czas CHECK (odjazd >= przyjazd),
    CONSTRAINT chk_kp_km CHECK (km_od_startu >= 0)
)
PARTITION BY RANGE (odjazd) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(PARTITION p_start VALUES LESS THAN (DATE '2020-01-01'));
-- Lokalny indeks wyszukiwania odjazdow; prefiks kompresowany, bo id_stacji powtarza sie masowo.
-- Uzasadnienie liczbami: database/perf/README.md.
CREATE INDEX ix_kp_stacja_odjazd ON kursy_postoje (id_stacji, odjazd) LOCAL COMPRESS 1;

CREATE TABLE rezerwacje (
    id_rezerwacji NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nr_biletu     VARCHAR2(20) NOT NULL,
    id_kursu      NUMBER NOT NULL,
    id_miejsca    NUMBER NOT NULL,
    id_stacji_od  NUMBER NOT NULL,
    id_stacji_do  NUMBER NOT NULL,
    lp_od         NUMBER(3,0) NOT NULL,
    lp_do         NUMBER(3,0) NOT NULL,
    pasazer       VARCHAR2(100) NOT NULL,
    email         VARCHAR2(120),
    telefon       VARCHAR2(20),
    cena          NUMBER(8,2) NOT NULL,
    status        VARCHAR2(10) DEFAULT 'OPLACONA' NOT NULL,
    klucz_idempotencji VARCHAR2(64),
    utworzono     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    anulowano     TIMESTAMP,
    CONSTRAINT uq_rez_bilet UNIQUE (nr_biletu),
    CONSTRAINT uq_rez_idempotencja UNIQUE (klucz_idempotencji),
    CONSTRAINT fk_rez_kurs FOREIGN KEY (id_kursu) REFERENCES kursy_rozkladowe (id_kursu),
    CONSTRAINT fk_rez_miejsce FOREIGN KEY (id_miejsca) REFERENCES miejsca (id_miejsca),
    CONSTRAINT fk_rez_od FOREIGN KEY (id_stacji_od) REFERENCES stacje (id_stacji),
    CONSTRAINT fk_rez_do FOREIGN KEY (id_stacji_do) REFERENCES stacje (id_stacji),
    CONSTRAINT chk_rez_status CHECK (status IN ('OPLACONA', 'ANULOWANA')),
    CONSTRAINT chk_rez_odcinek CHECK (lp_od < lp_do),
    CONSTRAINT chk_rez_kontakt CHECK (email IS NOT NULL OR telefon IS NOT NULL)
);
CREATE INDEX ix_rez_kurs_status ON rezerwacje (id_kursu, status);
CREATE INDEX ix_rez_miejsce ON rezerwacje (id_miejsca);
CREATE INDEX ix_rez_od ON rezerwacje (id_stacji_od);
CREATE INDEX ix_rez_do ON rezerwacje (id_stacji_do);

-- Ostatnia linia obrony przed overbookingiem: to miejsce moze byc zajete na danym
-- odcinku tylko raz. Bilety A-B i B-C na to samo miejsce sa dopuszczalne.
-- IOT: odczyt konfliktu nie dotyka segmentu tabeli.
CREATE TABLE rezerwacje_odcinki (
    id_kursu      NUMBER NOT NULL,
    id_miejsca    NUMBER NOT NULL,
    lp_odcinka    NUMBER(3,0) NOT NULL,
    id_rezerwacji NUMBER NOT NULL,
    CONSTRAINT pk_rez_odcinki PRIMARY KEY (id_kursu, id_miejsca, lp_odcinka),
    CONSTRAINT fk_ro_rezerwacja FOREIGN KEY (id_rezerwacji) REFERENCES rezerwacje (id_rezerwacji)
) ORGANIZATION INDEX;
CREATE INDEX ix_ro_rezerwacja ON rezerwacje_odcinki (id_rezerwacji);
